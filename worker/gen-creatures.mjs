// Writes src/creatures.js (slug -> name) from ../data/creatures.json so the Worker only accepts known
// creatures. Run before every deploy (deploy.sh does it) and before `wrangler dev`.
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const list = JSON.parse(readFileSync(new URL('../data/creatures.json', here), 'utf8'));
const map = Object.fromEntries(list.map((c) => [c.slug, c.name]));
// UFO slugs, so /v1/reports/nearby can filter ufo / creature / other.
const ufo = list.filter((c) => c.cat === 'ufo').map((c) => c.slug);
writeFileSync(new URL('src/creatures.js', here),
  '// Generated by gen-creatures.mjs from data/creatures.json. Do not edit.\n' +
  `export const CREATURES = ${JSON.stringify(map, null, 0)};\n` +
  `export const UFO = ${JSON.stringify(ufo)};\n`);
console.log(`creatures.js: ${list.length} creatures`);
